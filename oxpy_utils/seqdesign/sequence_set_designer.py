        self.__c_request_counts = dict()
        # map where keys are (len, gc) and values are sets of sequences with len and gc
        self.__c_candidates  = dict()

        # count how many sequences we want to have for each (len, gc) when we're done
        for domain_name, (domain_len, domain_gc) in self.requested_domains.items():
            self.__c_candidates[(domain_len, domain_gc)] = set() # redundant declaration is ok
            self.__c_request_counts[(domain_len, domain_gc)] = self.__c_request_counts[(domain_len, domain_gc)] + 1 \
                if (domain_len, domain_gc) in self.__c_request_counts else 1


