    def get_temp_range(self)->np.ndarray:
        temp_window = self.temperature_tolerance * 5
        return np.linspace(self.temperature - temp_window, self.temperature + temp_window, 21)

    def compute_melting_temp(self, all_seqs: list[str]) -> tuple[dict[str, list[float]],
                                                                 dict[str, list[float]]]:
        """
        shadows `compute_melting_temp` from `create_same_tm_seq_library.py`
        computes melting temperatures for the provided sequence
        """
        unbound_fractions = {seq: [] for seq in all_seqs}
        # compute unbound fractions for sequences
        for temp in self.get_temp_range():
            seq_wise_fractions = get_unbound_fraction(all_seqs, temp)
            for seq, frac in zip(all_seqs, seq_wise_fractions):
                unbound_fractions[seq].append(frac)

        # compute unbound fractions for sequences
        melting_temperatures = {}
        for seq, all_fracs in unbound_fractions.items():
            melt = self.get_temp_range()[np.abs(np.array(all_fracs) - 0.5).argmin()]
            melting_temperatures[seq] = melt

        return melting_temperatures, unbound_fractions

    def set_polyT(self, polyT_length: int, polyT_identifier: str = "_"):
        """
        sets the "default" polyT length
        by convention, the "default" poly-T is designated as domain "_" and further poly-Ts are
        designated by more underscores
        """
        self.domains[polyT_identifier] = "T" * polyT_length

    def get_sequences(self) -> list[str]:
        """
        returns DNA sequences for requested motifs
        """
        sequences = []
        for motif in self.motifs:
            seq = ""
            for domain in motif:
                if domain not in self.domains:
                    raise Exception(f"Domain {domain} has not been assigned a sequence!")
                seq += self.domains[domain]
            sequences.append(seq)
        return sequences

